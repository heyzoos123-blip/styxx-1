def _hazard_clean(fx) -> str | None:
    """H3's per-trial leftover (v5f outcome: 'leaves no profile or trace function behind (v5f has
    none to leave)'): no profile or trace function, the machinery quiet, f's __code__ restored."""
    bad = []
    if sys.getprofile() is not None:
        bad.append(f"profiler {{sys.getprofile()!r}}")
    if sys.gettrace() is not None:
        bad.append(f"trace function {{sys.gettrace()!r}}")
    st = P._v5_state()
    if st["mints"] or st["anchors"] or st["global_events"]:
        bad.append(f"machinery not quiet: mints {{len(st['mints'])}}, anchors {{st['anchors']}}, "
                   f"global_events {{st['global_events']}}")
    if fx.f.__code__ is not _HAZ_CODES.get("f", fx.f.__code__):
        bad.append("f.__code__ not restored")
    return "; ".join(bad) or None


