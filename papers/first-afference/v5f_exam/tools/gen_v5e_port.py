def build():
    raw = open(SRC, "rb").read()
    sha = hashlib.sha256(raw).hexdigest()
    src = raw.decode("utf-8")
    parts = []
    for a, b in REGIONS:
        i = src.index(a)
        j = src.index(b, i)
        parts.append(src[i:j])
    body = "\n".join(parts)
    for why, old, new in PORT:
        assert body.count(old) == 1, (why, old)
        body = body.replace(old, new)
    return sha, HEADER.format(sha=sha) + body


def main(argv):
    sha, text = build()
    if SRC_SHA256 != "__FILL__" and sha != SRC_SHA256:
        raise SystemExit(f"run_protocol_v5e.py changed: sha256 {sha}, frozen {SRC_SHA256}")
    if "--check" in argv:
        same = os.path.exists(OUT) and open(OUT, encoding="utf-8").read() == text
        print("v5e_port.py: " + ("reproduced" if same else "DIFFERS"))
        return 0 if same else 1
    open(OUT, "w", encoding="utf-8").write(text)
    print(f"wrote {OUT} from run_protocol_v5e.py sha256 {sha}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
